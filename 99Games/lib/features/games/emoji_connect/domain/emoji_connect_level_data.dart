  static List<EmojiConnectLevel> getLevelsForDifficulty(
    EmojiConnectDifficulty difficulty,
  ) {
    return switch (difficulty) {
      EmojiConnectDifficulty.easy => easyLevels,
      EmojiConnectDifficulty.medium => mediumLevels,
      EmojiConnectDifficulty.hard => hardLevels,
    };
  }

  static EmojiConnectLevel getLevel(
    EmojiConnectDifficulty difficulty,
    int levelNumber,
  ) {
    final levels = getLevelsForDifficulty(difficulty);
    final index = (levelNumber - 1).clamp(0, levels.length - 1);
    return levels[index];
  }
